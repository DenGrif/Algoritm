# Шаг 1: Определяем функцию, которая принимает одну строку в качестве аргумента.
# Шаг 2: Преобразуем строку в нижний регистр, чтобы проверка была нечувствительной к регистру.
# Шаг 3: Удаляем из строки все неалфавитно-цифровые символы, чтобы сосредоточиться только на буквах и цифрах.
# Шаг 4: Переворачиваем очищенную строку.
# Шаг 5: Сравниваем очищенную строку с её перевёрнутой версией.
# Шаг 6: Возвращаем True, если они совпадают, в противном случае возвращаем False.


def is_palindrome(s):
    # Преобразуем строку в нижний регистр
    s = s.lower()

    # Удаляем неалфавитно-цифровые символов
    s = ''.join(char for char in s if char.isalnum())

    # Переворачивание строки
    reversed_s = s[::-1]

    # Проверка, совпадают ли оригинальная и перевёрнутая строки
    return s == reversed_s

# Пример использования
print(is_palindrome("A man, a plan, a canal, Panama"))
print(is_palindrome("racecar"))
print(is_palindrome("hello"))
print(is_palindrome("Madam"))
